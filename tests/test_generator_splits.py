"""Committed provenance is executable for every learning split family."""
from collections import Counter
from collections.abc import Callable
import hashlib
import importlib
import json
from pathlib import Path
import random
from typing import cast

import pytest

from pypddl_datasets.generators.runtime import (
    DISTRIBUTION_REVISION, Problem, RandomSource, Rejected, render_problem,
    semantic_fingerprint,
)
from pypddl_datasets.generators.splits import (
    SPLITS, Split, SplitRecipe, balanced_schedule, derive_seed, parameter_values,
)

ROOT = Path(__file__).resolve().parents[1]
DOMAINS = sorted(path.parent.name for path in
                 (ROOT / "src/pypddl_datasets/generators/classical").glob("*/generate_instances.py"))


def _record_parameters(record: dict[str, object]) -> str:
    return json.dumps(record["parameters"], sort_keys=True)


@pytest.mark.parametrize("domain", DOMAINS)
@pytest.mark.parametrize("split", SPLITS)
def test_committed_manifest_and_replay(domain: str, split: Split) -> None:
    module = importlib.import_module(f"pypddl_datasets.generators.classical.{domain}.generate_instances")
    recipe = cast(SplitRecipe[object], module.RECIPE)
    # These immutable revision-2 corpora were generated by the Python samplers.
    # ProbLog preserves their law, but its random draw order need not preserve a
    # seed-to-task mapping. Replay the frozen historical algorithms here; current
    # samplers have separate exhaustive probability and membership checks.
    sampler_module = (importlib.import_module(f"reference_generators.{domain}")
                      if domain in {"ferry", "delivery"} else module)
    sample = cast(Callable[[object, RandomSource], Problem | Rejected], sampler_module.sample)
    directory = ROOT / "data/classical/generated" / f"{domain}-{split}"
    manifest = cast("dict[str, object]", json.loads((directory / "manifest.json").read_text()))
    records = cast("list[dict[str, object]]", manifest["instances"])
    assert manifest["distribution_revision"] == DISTRIBUTION_REVISION
    assert manifest["domain_sha256"] == hashlib.sha256(recipe.domain_path.read_bytes()).hexdigest()
    assert len(records) == recipe.counts[split]
    schedule = _check_schedule(recipe, split, records, cast(int, manifest["master_seed"]))
    _check_provenance(directory, records, cast(int, manifest["master_seed"]), domain, split)
    # Replay both ends of every split, checking semantics and exact serialization.
    for index in sorted({0, len(records) - 1}):
        record = records[index]
        problem = sample(schedule[index], random.Random(cast(int, record["seed"])))
        assert isinstance(problem, Problem)
        assert semantic_fingerprint(problem) == record["semantic_sha256"]
        assert render_problem(problem) == (directory / cast(str, record["file"])).read_text()


def _check_schedule(recipe: SplitRecipe[object], split: Split,
                    records: list[dict[str, object]], master_seed: int) -> list[object]:
    counts = Counter(_record_parameters(record) for record in records)
    size = len(recipe.spaces[split])
    assert all(len(records) // size <= counts[json.dumps(parameter_values(config), sort_keys=True)]
               <= (len(records) + size - 1) // size for config in recipe.spaces[split])
    schedule = balanced_schedule(recipe.spaces[split], len(records),
                                 derive_seed(master_seed, recipe.domain, split, "schedule"))
    assert [record["parameters"] for record in records] == [parameter_values(config) for config in schedule]
    return schedule


def _check_provenance(directory: Path, records: list[dict[str, object]],
                      master_seed: int, domain: str, split: Split) -> None:
    for index, record in enumerate(records, start=1):
        content = (directory / cast(str, record["file"])).read_bytes()
        assert record["sha256"] == hashlib.sha256(content).hexdigest()
        attempts = cast(list[int], record["attempt_seeds"])
        assert attempts == [derive_seed(master_seed, domain, split, "attempt", index, attempt)
                            for attempt in range(cast(int, record["rejected_attempts"]) + 1)]
        assert attempts[-1] == record["seed"]
